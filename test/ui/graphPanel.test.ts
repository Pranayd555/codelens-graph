import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import * as vm from 'node:vm';
import { toWebviewData, getGraphPanelHtml } from '../../src/ui/graphPanel';
import { GraphNode, GraphEdge, NodeType, EdgeType } from '../../src/types';
import { scriptTags, cspDirectives } from './_webview';

const NONCE = '0123456789abcdef0123456789abcdef';
const D3_URI = 'https://file+.vscode-resource.vscode-cdn.net/ext/dist/node_modules/d3/dist/d3.min.js';

function node(id: string, name: string, type: NodeType, filePath: string, extra: Partial<GraphNode> = {}): GraphNode {
  return { id, name, type, filePath, line: 3, endLine: 9, language: 'typescript', updatedAt: 1, ...extra };
}

function edge(fromId: string, toId: string, type: EdgeType): GraphEdge {
  return { id: `${fromId}->${toId}:${type}`, fromId, toId, type, metadata: { note: 'dropped' } };
}

// The value the webview script sees for RAW, evaluated as JavaScript (as the browser does).
function embeddedData(html: string): unknown {
  const inline = scriptTags(html).find(t => !t.src);
  assert.ok(inline, 'inline script present');
  const m = /\nlet RAW = ([\s\S]*?);\n\n\/\/ ── Config/.exec(inline.body);
  assert.ok(m, 'RAW assignment found');
  return vm.runInThisContext(`(${m[1]})`);
}

describe('graphPanel.toWebviewData', () => {
  it('maps nodes to the webview shape and drops everything else', () => {
    const data = toWebviewData([
      node('n1', 'run', 'function', '/ws/src/run.ts', {
        signature: 'run(): void', docComment: 'secret docs', localVars: ['x'], params: [{ name: 'a' }],
      }),
    ], []);
    assert.deepEqual(data, {
      nodes: [{ id: 'n1', name: 'run', type: 'function', file: '/ws/src/run.ts', line: 3, undefinedRefs: [], isConfig: false }],
      edges: [],
    });
  });

  it('carries undefinedRefs through and defaults them to []', () => {
    const data = toWebviewData([
      node('a', 'a', 'function', '/ws/a.ts', { undefinedRefs: ['fooo', 'barr'] }),
      node('b', 'b', 'function', '/ws/b.ts'),
      node('c', 'c', 'function', '/ws/c.ts', { undefinedRefs: [] }),
    ], []);
    assert.deepEqual(data.nodes.map(n => n.undefinedRefs), [['fooo', 'barr'], [], []]);
  });

  it('flags config and documentation files with isConfig', () => {
    const files: [string, boolean][] = [
      ['/ws/package.json', true],
      ['/ws/tsconfig.json', true],
      ['/ws/web/vite.config.ts', true],
      ['/ws/docs/guide.md', true],
      ['C:\\ws\\README.md', true],
      ['/ws/src/index.ts', false],
      ['/ws/.codelens/skills/x.md', false],   // generated by CodeLens
      ['/ws/CLAUDE.md', false],               // generated by CodeLens
    ];
    const data = toWebviewData(files.map(([f], i) => node(String(i), 'n' + i, 'variable', f)), []);
    assert.deepEqual(data.nodes.map(n => [n.file, n.isConfig]), files);
  });

  it('does not filter nodes: import, node_modules and config nodes are kept in order (the webview filters)', () => {
    const nodes = [
      node('1', 'fs', 'import', '/ws/src/a.ts'),
      node('2', 'lodash', 'function', '/ws/node_modules/lodash/index.js'),
      node('3', 'cfg', 'variable', '/ws/vite.config.ts'),
      node('4', 'File', 'file', '/ws/src/a.ts'),
    ];
    assert.deepEqual(toWebviewData(nodes, []).nodes.map(n => n.id), ['1', '2', '3', '4']);
  });

  it('maps edges to source/target/type, keeps hyphenated types and dangling endpoints, drops id/metadata', () => {
    const data = toWebviewData([node('a', 'a', 'function', '/ws/a.ts')], [
      edge('a', 'b', 'calls'),
      edge('pkg:x', 'pkg:y', 'depends-on'),
      edge('a', 'missing', 'peer-dependency'),
    ]);
    assert.deepEqual(data.edges, [
      { source: 'a', target: 'b', type: 'calls' },
      { source: 'pkg:x', target: 'pkg:y', type: 'depends-on' },
      { source: 'a', target: 'missing', type: 'peer-dependency' },
    ]);
  });

  it('handles an empty graph', () => {
    assert.deepEqual(toWebviewData([], []), { nodes: [], edges: [] });
  });
});

describe('graphPanel.getGraphPanelHtml', () => {
  const sample = toWebviewData(
    [node('a', 'alpha', 'class', '/ws/a.ts'), node('b', 'beta', 'method', '/ws/a.ts', { undefinedRefs: ['gamma'] })],
    [edge('a', 'b', 'contains')]
  );

  it('sets a nonce-based CSP with no other script sources', () => {
    const html = getGraphPanelHtml(sample, NONCE, D3_URI);
    const csp = cspDirectives(html);
    assert.deepEqual(csp, {
      'default-src': ["'none'"],
      'script-src': [`'nonce-${NONCE}'`],
      'style-src': ["'unsafe-inline'"],
    });
    assert.ok(html.indexOf('Content-Security-Policy') < html.indexOf('<script'), 'CSP is declared before any script');
  });

  it('puts the nonce on every script tag; the only external script is the given d3 URI', () => {
    const html = getGraphPanelHtml(sample, NONCE, D3_URI);
    const tags = scriptTags(html);
    assert.equal(tags.length, 2);
    assert.equal((html.match(/<script\b/gi) ?? []).length, tags.length, 'every <script is a well-formed tag');
    for (const tag of tags) { assert.equal(tag.nonce, NONCE, `nonce on <script${tag.attrs}>`); }
    assert.deepEqual(tags.map(t => t.src), [D3_URI, null]);
    assert.equal(tags[0].body.trim(), '', 'the d3 tag has no inline body');
  });

  it('loads nothing else remotely and has no inline event handlers (the CSP would block them)', () => {
    const html = getGraphPanelHtml(sample, NONCE, D3_URI);
    const withoutD3 = html.split(D3_URI).join('');
    assert.doesNotMatch(withoutD3, /\b(?:https?:)?\/\/[a-z0-9.-]+\.[a-z]{2,}/i, 'no remote URLs');
    const markup = html.replace(/<script\b[\s\S]*?<\/script>/gi, '');
    assert.doesNotMatch(markup, /\s(?:src|href|action|srcset)\s*=/i, 'no other src/href attributes');
    assert.doesNotMatch(markup, /<(?:link|iframe|img|object|embed|base|form)\b/i);
    assert.doesNotMatch(markup, /\son[a-z]+\s*=/i);
  });

  it('embeds the graph data so the script sees exactly the input', () => {
    const html = getGraphPanelHtml(sample, NONCE, D3_URI);
    assert.deepEqual(embeddedData(html), sample);
    assert.deepEqual(embeddedData(getGraphPanelHtml({ nodes: [], edges: [] }, NONCE, D3_URI)), { nodes: [], edges: [] });
  });

  it('escapes hostile names and paths so they cannot break out of the script block', () => {
    const hostile = [
      '</script><img src=x onerror=alert(1)>',
      `"';`,
      '</SCRIPT >',
      '<!--<script>',
      '`${alert(1)}`',
      'line\u2028sep\u2029para',
      '\\"); alert(1); //',
    ];
    const data = toWebviewData(
      hostile.map((name, i) => node('id' + i + name, name, 'function', `C:\\ws\\${name}\\x.ts`, { undefinedRefs: [name] })),
      [edge('id0' + hostile[0], 'id1' + hostile[1], 'calls')]
    );
    const html = getGraphPanelHtml(data, NONCE, D3_URI);

    // The HTML tokenizer only sees the two script tags we wrote.
    assert.equal((html.match(/<\/script/gi) ?? []).length, 2, 'no extra </script> sequences');
    assert.equal((html.match(/<script/gi) ?? []).length, 2, 'no extra <script> sequences');
    assert.ok(!html.includes('<!--'), 'no <!-- inside the script (script-data escape state)');
    assert.ok(!html.includes('<img'), 'injected markup is not present');

    // The script still parses, and the data round-trips unchanged.
    const inline = scriptTags(html).find(t => !t.src)!;
    assert.doesNotThrow(() => new vm.Script(inline.body));
    assert.deepEqual(embeddedData(html), data);
  });
});
